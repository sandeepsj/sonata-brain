-- REQ-057..059, REQ-070..076, REQ-082: school-wide fee structures on a timeline; dues derived from facts.

-- 1. Keep the legacy term model read-only for the comparison report (REQ-082.AC4).
ALTER TABLE fee_structure RENAME TO legacy_fee_structure;
ALTER TABLE fee_dues_tracker RENAME TO legacy_fee_dues;

-- 2. Payments no longer point at a term (REQ-082.AC2). Every legacy REGULAR payment already has its course.
ALTER TABLE payments DROP COLUMN term_id;
ALTER TABLE payments ADD CONSTRAINT payments_regular_needs_course
    CHECK (payment_type <> 'REGULAR' OR course_name IS NOT NULL);                       -- REQ-061.AC7

-- 3. New model.
CREATE TABLE fee_structure (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    term_months integer      NOT NULL CHECK (term_months BETWEEN 1 AND 12)
);
CREATE UNIQUE INDEX fee_structure_name_uk ON fee_structure (lower(name));

CREATE TABLE fee_structure_amount (
    fee_structure_id bigint        NOT NULL REFERENCES fee_structure (id) ON DELETE CASCADE,
    course_name      varchar(255)  NOT NULL REFERENCES course (name),
    amount           numeric(10,2) NOT NULL CHECK (amount >= 0),
    PRIMARY KEY (fee_structure_id, course_name)
);

CREATE TABLE fee_timeline_entry (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_structure_id bigint NOT NULL REFERENCES fee_structure (id),
    effective_from   date   NOT NULL UNIQUE
);

CREATE TABLE fee_due (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id       bigint        NOT NULL REFERENCES student (admission_no),
    course_name      varchar(255)  NOT NULL REFERENCES course (name),
    period_start     date          NOT NULL,
    period_end       date          NOT NULL,
    fee_structure_id bigint        NOT NULL REFERENCES fee_structure (id),
    amount           numeric(10,2) NOT NULL,
    paid_amount      numeric(10,2) NOT NULL,
    discount_amount  numeric(10,2) NOT NULL,
    balance          numeric(10,2) NOT NULL,
    status           varchar(16)   NOT NULL CHECK (status IN ('DUE', 'PARTIALLY_PAID', 'PAID')),
    UNIQUE (student_id, course_name, period_start)
);
CREATE INDEX fee_due_course_idx ON fee_due (course_name, period_start);

-- 4. Legacy years become structures on the timeline (REQ-082.AC1). Each year must use whole-month terms and charge
--    each course one amount; otherwise the migration stops so the data can be looked at.
DO $$
DECLARE
    y            record;
    months       integer;
    prev_id      bigint;
    prev_months  integer;
    new_id       bigint;
    same         boolean;
BEGIN
    FOR y IN SELECT year, count(DISTINCT term)::int AS terms FROM legacy_fee_structure GROUP BY year ORDER BY year LOOP
        IF 12 % y.terms <> 0 THEN
            RAISE EXCEPTION 'Legacy year % has % terms, which does not divide 12', y.year, y.terms;
        END IF;
        IF EXISTS (SELECT 1 FROM legacy_fee_structure WHERE year = y.year
                   GROUP BY course_id HAVING count(DISTINCT amount) > 1) THEN
            RAISE EXCEPTION 'Legacy year % charges different amounts per term for a course', y.year;
        END IF;
        months := 12 / y.terms;

        same := prev_id IS NOT NULL AND prev_months = months AND NOT EXISTS (
            (SELECT course_id, max(amount) FROM legacy_fee_structure WHERE year = y.year GROUP BY course_id
             EXCEPT SELECT course_name, amount FROM fee_structure_amount WHERE fee_structure_id = prev_id)
            UNION ALL
            (SELECT course_name, amount FROM fee_structure_amount WHERE fee_structure_id = prev_id
             EXCEPT SELECT course_id, max(amount) FROM legacy_fee_structure WHERE year = y.year GROUP BY course_id));

        IF NOT same THEN
            INSERT INTO fee_structure (name, term_months) VALUES ('Fees ' || y.year, months) RETURNING id INTO new_id;
            INSERT INTO fee_structure_amount (fee_structure_id, course_name, amount)
                SELECT new_id, course_id, max(amount) FROM legacy_fee_structure WHERE year = y.year GROUP BY course_id;
            INSERT INTO fee_timeline_entry (fee_structure_id, effective_from) VALUES (new_id, make_date(y.year, 1, 1));
            prev_id := new_id;
            prev_months := months;
        END IF;
    END LOOP;
END $$;

-- 5. Legacy "student left" cancellations become ₹0 course-fee payments with a discount for the cancelled amount
--    (REQ-082.AC6, REQ-072.AC6). The discount fills the oldest open term of that course.
DO $$
DECLARE
    d   record;
    pid bigint;
BEGIN
    FOR d IN
        SELECT ss.student_id, fs.course_id, l.due_amount,
               make_date(fs.year, (fs.term - 1) * (12 / t.terms) + 1, 1) AS term_start
        FROM legacy_fee_dues l
        JOIN student_sessions ss ON ss.id = l.student_session_id
        JOIN legacy_fee_structure fs ON fs.id = l.fee_structure_id
        JOIN (SELECT year, count(DISTINCT term)::int AS terms FROM legacy_fee_structure GROUP BY year) t ON t.year = fs.year
        WHERE l.status = 'STUDENT_LEFT_DUE_CANCELLED' AND l.due_amount > 0
        ORDER BY l.id
    LOOP
        INSERT INTO payments (student_id, payment_type, course_name, amount_paid, discount_amount, date, label, remarks,
                              is_active, created_at)
        VALUES (d.student_id, 'REGULAR', d.course_id, 0, d.due_amount, d.term_start, 'Forgiven: student left (migrated)',
                'Was a STUDENT_LEFT_DUE_CANCELLED due', true, now())
        RETURNING id INTO pid;
        INSERT INTO discounts (payment_id, discount_amount, label, created_at)
        VALUES (pid, d.due_amount, 'Forgiven: student left', now());
    END LOOP;
END $$;

