-- REQ-011/012/013, REQ-080.AC5: per-resource permissions grouped into named roles, replacing account.scope.

CREATE TABLE role (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL UNIQUE,
    description varchar(500),
    built_in    boolean      NOT NULL DEFAULT false
);

-- One row per resource the role can access. A resource without a row means NONE.
CREATE TABLE role_permission (
    role_id  bigint      NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    resource varchar(32) NOT NULL
        CHECK (resource IN ('STUDENT', 'SESSION', 'PAYMENT', 'COURSE', 'FEE_STRUCTURE', 'DUES', 'USER')),
    access   varchar(8)  NOT NULL CHECK (access IN ('READ', 'WRITE')),
    PRIMARY KEY (role_id, resource)
);

CREATE TABLE user_roles (
    user_id bigint NOT NULL REFERENCES account (user_id) ON DELETE CASCADE,
    role_id bigint NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

INSERT INTO role (name, description, built_in) VALUES ('ADMIN', 'Full access to everything', true);

INSERT INTO role_permission (role_id, resource, access)
SELECT r.id, res.resource, 'WRITE'
FROM role r
CROSS JOIN (VALUES ('STUDENT'), ('SESSION'), ('PAYMENT'), ('COURSE'), ('FEE_STRUCTURE'), ('DUES'), ('USER')) AS res (resource)
WHERE r.name = 'ADMIN';

-- Accounts that had full access (scope ANY) become administrators; everyone else starts with no roles.
INSERT INTO user_roles (user_id, role_id)
SELECT a.user_id, r.id FROM account a, role r WHERE a.scope = 'ANY' AND r.name = 'ADMIN';

ALTER TABLE account DROP COLUMN scope;
