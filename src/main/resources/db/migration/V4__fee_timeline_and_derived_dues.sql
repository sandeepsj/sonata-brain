-- Fee structures become reusable templates placed on a per-course timeline; payments point at a period by date;
-- dues become a derived table that can be rebuilt at any time. (REQ-050..056, REQ-060..066, REQ-070..076, REQ-080)

-- 1. Keep the legacy tables under legacy_ names (REQ-080.AC4).
ALTER TABLE fee_structure RENAME TO legacy_fee_structure;
ALTER SEQUENCE fee_structure_id_seq RENAME TO legacy_fee_structure_id_seq;
ALTER TABLE fee_dues_tracker RENAME TO legacy_fee_dues_tracker;
ALTER SEQUENCE fee_dues_tracker_id_seq RENAME TO legacy_fee_dues_tracker_id_seq;

-- 2. Fee structure templates and the timeline.
CREATE TABLE fee_structure (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(200) NOT NULL,
    course_name    varchar(255) NOT NULL REFERENCES course (name),
    terms_per_year integer      NOT NULL CHECK (terms_per_year IN (1, 2, 3, 4, 6, 12)),
    created_at     timestamp(6) NOT NULL,
    UNIQUE (course_name, name)
);

CREATE TABLE fee_structure_term (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_structure_id bigint        NOT NULL REFERENCES fee_structure (id) ON DELETE CASCADE,
    term_number      integer       NOT NULL CHECK (term_number >= 1),
    amount           numeric(10, 2) NOT NULL CHECK (amount >= 0),
    UNIQUE (fee_structure_id, term_number)
);

CREATE TABLE fee_timeline_entry (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name      varchar(255) NOT NULL REFERENCES course (name),
    fee_structure_id bigint       NOT NULL REFERENCES fee_structure (id),
    effective_from   date         NOT NULL,
    effective_to     date,
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX idx_fee_timeline_course ON fee_timeline_entry (course_name, effective_from);

-- 3. Payments: the period they pay for, and conversion audit (REQ-060, REQ-065).
ALTER TABLE payments RENAME COLUMN term_id TO legacy_term_id;
ALTER TABLE payments ADD COLUMN period_date date;
ALTER TABLE payments ADD COLUMN original_type varchar(16);
ALTER TABLE payments ADD COLUMN converted_at timestamp(6);
ALTER TABLE payments ADD COLUMN converted_by varchar(255);

-- 4. Waivers: manual decisions that survive rebuilds (REQ-072).
CREATE TABLE due_waiver (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_session_id bigint       NOT NULL REFERENCES student_sessions (id) ON DELETE CASCADE,
    period_start       date         NOT NULL,
    reason             varchar(500) NOT NULL,
    created_by         varchar(255) NOT NULL,
    created_at         timestamp(6) NOT NULL,
    UNIQUE (student_session_id, period_start)
);

-- 5. Derived dues (REQ-070) and rebuild job records (REQ-074).
CREATE TABLE fee_due (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_session_id bigint         NOT NULL REFERENCES student_sessions (id) ON DELETE CASCADE,
    student_id         bigint         NOT NULL REFERENCES student (admission_no),
    course_name        varchar(255)   NOT NULL,
    fee_structure_id   bigint         REFERENCES fee_structure (id) ON DELETE SET NULL,
    period_start       date           NOT NULL,
    period_end         date           NOT NULL,
    term_number        integer        NOT NULL,
    terms_per_year     integer        NOT NULL,
    amount             numeric(10, 2) NOT NULL,
    paid_amount        numeric(10, 2) NOT NULL,
    discount_amount    numeric(10, 2) NOT NULL,
    balance            numeric(10, 2) NOT NULL,
    overpaid_amount    numeric(10, 2) NOT NULL,
    status             varchar(20)    NOT NULL
        CHECK (status IN ('DUE', 'PARTIALLY_PAID', 'PAID', 'OVERPAID', 'WAIVED')),
    computed_at        timestamp(6)   NOT NULL,
    UNIQUE (student_session_id, period_start)
);
CREATE INDEX idx_fee_due_student ON fee_due (student_id, period_start);
CREATE INDEX idx_fee_due_course ON fee_due (course_name, period_start);

CREATE TABLE dues_rebuild_job (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope        varchar(16)  NOT NULL,
    scope_id     varchar(255),
    dry_run      boolean      NOT NULL,
    status       varchar(16)  NOT NULL,
    created      integer      NOT NULL DEFAULT 0,
    updated      integer      NOT NULL DEFAULT 0,
    deleted      integer      NOT NULL DEFAULT 0,
    errors       text         NOT NULL DEFAULT '[]',
    changes      text         NOT NULL DEFAULT '[]',
    triggered_by varchar(255),
    started_at   timestamp(6) NOT NULL,
    finished_at  timestamp(6)
);

-- 6. Move legacy data (REQ-080).
-- Each (course, year) of legacy rows becomes one template "<course> <year>" ...
INSERT INTO fee_structure (name, course_name, terms_per_year, created_at)
SELECT course_id || ' ' || year, course_id, count(*), now()
FROM legacy_fee_structure
GROUP BY course_id, year;

INSERT INTO fee_structure_term (fee_structure_id, term_number, amount)
SELECT fs.id, l.term, l.amount
FROM legacy_fee_structure l
JOIN fee_structure fs ON fs.course_name = l.course_id AND fs.name = l.course_id || ' ' || l.year;

-- ... placed on the timeline for that calendar year.
INSERT INTO fee_timeline_entry (course_name, fee_structure_id, effective_from, effective_to)
SELECT DISTINCT l.course_id, fs.id, make_date(l.year, 1, 1), make_date(l.year, 12, 31)
FROM legacy_fee_structure l
JOIN fee_structure fs ON fs.course_name = l.course_id AND fs.name = l.course_id || ' ' || l.year;

-- Start date of each legacy term: the year is split into terms_per_year equal blocks of months.
CREATE TEMPORARY TABLE legacy_term_start AS
SELECT l.id AS legacy_id,
       make_date(l.year, (l.term - 1) * (12 / n.terms) + 1, 1) AS period_start
FROM legacy_fee_structure l
JOIN (SELECT course_id, year, count(*)::int AS terms FROM legacy_fee_structure GROUP BY course_id, year) n
  ON n.course_id = l.course_id AND n.year = l.year;

UPDATE payments p SET period_date = t.period_start
FROM legacy_term_start t
WHERE p.legacy_term_id = t.legacy_id AND p.payment_type = 'REGULAR';

INSERT INTO due_waiver (student_session_id, period_start, reason, created_by, created_at)
SELECT d.student_session_id, t.period_start,
       'Migrated from legacy status STUDENT_LEFT_DUE_CANCELLED', 'migration',
       coalesce(d.updated_at, d.created_at)
FROM legacy_fee_dues_tracker d
JOIN legacy_term_start t ON t.legacy_id = d.fee_structure_id
WHERE d.status = 'STUDENT_LEFT_DUE_CANCELLED';

DROP TABLE legacy_term_start;

-- Only now can every course-fee payment be required to name a course and a period (REQ-061.AC5).
ALTER TABLE payments ADD CONSTRAINT payments_regular_needs_course_and_period
    CHECK (payment_type = 'ADDITIONAL' OR (course_name IS NOT NULL AND period_date IS NOT NULL));
